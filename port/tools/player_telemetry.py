#!/usr/bin/env python3
"""Read-only ASMP player/floor/camera telemetry, shared by DS and native probes.

All position fields are signed Fix12 integers. GroundY is the player's stored
floor height, not a fresh ray; sphere correction and ray results are included
separately. Body matrix translations are native render units (world / 8).
No tool in this module writes emulated game RAM.
"""
import argparse
import hashlib
import json
import re
import struct
from pathlib import Path

SCHEMA = "sm64ds-player-telemetry-v1"
PLAYER_FIELDS = {
    "position_fx12": (0x5c, "i", 3),
    "scale_fx12": (0x80, "i", 3),
    "collider_flags": (0x390, "I", 1),
    "sphere_center_fx12": (0x3dc, "i", 3),
    "sphere_radius_fx12": (0x3e8, "i", 1),
    "sphere_correction_fx12": (0x3ec, "i", 3),
    "sphere_hit_flags": (0x410, "B", 1),
    "ray_has_hit": (0x504, "B", 1),
    "ray_hit_fx12": (0x508, "i", 3),
    "floor_normal_fx12": (0x554, "i", 3),
    "ground_y_fx12": (0x644, "i", 1),
    "sink_depth_fx12": (0x68c, "i", 1),
    "body_yoffset_fx12": (0x690, "i", 1),
    "character": (0x6d9, "B", 1),
    "body_model_id": (0x6db, "B", 1),
}
CAMERA_FIELDS = {
    "look_at_fx12": (0x80, "i", 3),
    "position_fx12": (0x8c, "i", 3),
    "flags": (0x154, "I", 1),
    "fov_interp_fx12": (0x168, "i", 1),
    "half_fov_field": (0x17a, "h", 1),
}
GLOBAL_FIELDS = {
    "level": (0x0209f2f8, "B", 1),
    "message": (0x0209d660, "B", 1),
    "message_phase": (0x0209d6bc, "B", 1),
    "script_active": (0x0209fc48, "I", 1),
    "persistent_flags": (0x0209caa4, "I", 1),
    "transient_flags": (0x0209caa8, "I", 1),
}

def inspect_ram(path, checkpoint="snapshot", updates=0, keys=0):
    path = Path(path)
    data = path.read_bytes()
    if len(data) != 4 * 1024 * 1024:
        raise ValueError("Expected the runner's 4 MiB MainRAM snapshot")
    def read(address, fmt="I", count=1):
        offset = address - 0x02000000
        if not 0 <= offset <= len(data) - struct.calcsize(fmt) * count:
            raise ValueError(f"Address outside main RAM: {address:#x}")
        values = struct.unpack_from("<" + fmt * count, data, offset)
        return values[0] if count == 1 else list(values)
    player, camera = read(0x0209f394), read(0x0209f318)
    if read(player) != 0x0210a83c:
        raise ValueError("Expected live ASMP Player vtable")
    result = {"schema": SCHEMA, "checkpoint": checkpoint, "updates": updates,
              "keys": keys, "ram_sha256": hashlib.sha256(data).hexdigest()}
    result.update({name: read(*spec) for name, spec in GLOBAL_FIELDS.items()})
    for key, address, fields in [("player", player, PLAYER_FIELDS), ("camera", camera, CAMERA_FIELDS)]:
        result[key] = {name: read(address + off, fmt, count) for name, (off, fmt, count) in fields.items()}
    result["player"]["body_matrices_fx12"] = [
        read(ptr + 0x1c, "i", 12) if (ptr := read(player + 0xdc + slot * 4)) else None
        for slot in range(4)]
    return result

def emit_header(path):
    # JSON string escaping is also valid escaping for these ASCII C++ literals.
    def printf(fmt, *args):
        return 'std::printf(' + json.dumps(fmt) + (', ' + ', '.join(args) if args else '') + ');'
    lines = ['// Generated by port/tools/player_telemetry.py; do not edit.',
             '#pragma once', '#include <cstdio>', '#include <cstdint>', '#include <cstring>',
             'namespace player_telemetry {',
             'static_assert(sizeof(void*) == 4, "Collector requires the ARM32 original layout");',
             'template<class T> inline T read(const void* base, unsigned offset) { T value; std::memcpy(&value, static_cast<const char*>(base)+offset, sizeof(value)); return value; }',
             'inline void collect(const char* checkpoint, unsigned updates, unsigned keys, const void* player, const void* camera, unsigned level, unsigned message, unsigned message_phase, unsigned script_active, unsigned persistent_flags, unsigned transient_flags) {',
             printf('PLAYER_TELEMETRY {"schema":"'+SCHEMA+'","checkpoint":"%s","updates":%u,"keys":%u,"level":%u,"message":%u,"message_phase":%u,"script_active":%u,"persistent_flags":%u,"transient_flags":%u', 'checkpoint', 'updates', 'keys', 'level', 'message', 'message_phase', 'script_active', 'persistent_flags', 'transient_flags')]
    types = {"i": "std::int32_t", "I": "std::uint32_t", "B": "std::uint8_t", "h": "std::int16_t"}
    for obj, fields in [("player", PLAYER_FIELDS), ("camera", CAMERA_FIELDS)]:
        lines.append(printf(',"'+obj+'":{'))
        for idx, (name, (offset, fmt, count)) in enumerate(fields.items()):
            values = [f'read<{types[fmt]}>({obj}, 0x{offset + n * struct.calcsize(fmt):x})' for n in range(count)]
            formatstr = ('[' + ','.join(['%d'] * count) + ']') if count > 1 else ('%u' if fmt in 'IB' else '%d')
            lines.append(printf((',' if idx else '')+'"'+name+'":'+formatstr, *values))
        if obj == 'player':
            lines.extend([printf(',"body_matrices_fx12":['),
                'for(unsigned slot=0;slot<4;++slot){ if(slot)std::printf(","); auto* model=read<const void*>(player,0xdc+slot*4); if(!model){std::printf("null");continue;} std::printf("["); for(unsigned i=0;i<12;++i)std::printf(i?",%d":"%d",read<std::int32_t>(model,0x1c+i*4));std::printf("]"); }', printf(']')])
        lines.append(printf('}'))
    lines += [printf('}\n'), '}', '}']
    Path(path).write_text("\n".join(lines) + "\n")

def emit_route_header(route_path, output):
    route = json.loads(Path(route_path).read_text())
    segments = route["segments"]
    if not segments or route["level"] != 2:
        raise ValueError("Expected a nonempty castle-interior route")
    lines = ["// Generated from " + str(route_path) + "; buttons only.",
             "#pragma once", "struct PlayerRouteSegment { const char* checkpoint; unsigned updates; unsigned short keys; };",
             "static const unsigned playerRouteSettle = " + str(int(route.get("settle_updates",60))) + ";",
             "static const PlayerRouteSegment playerRouteSegments[] = {"]
    for item in segments:
        label, updates, keys = item["checkpoint"], item["updates"], item["keys"]
        if not re.fullmatch(r"[a-zA-Z0-9_-]+", label) or not 1 <= updates <= 1200 or not 0 <= keys <= 0xfff:
            raise ValueError("Invalid button segment")
        lines.append("    {" + json.dumps(label) + ", " + str(updates) + ", " + hex(keys) + "},")
    lines += ["};", "static const unsigned playerRouteLength = " + str(sum(i["updates"] for i in segments)) + ";"]
    Path(output).write_text("\n".join(lines)+"\n")

def read_records(path):
    text = Path(path).read_text()
    try:
        value = json.loads(text)
        records = value if isinstance(value, list) else ([value] if value.get("schema") == SCHEMA else value["samples"])
    except json.JSONDecodeError:
        records = [json.loads(line.split("PLAYER_TELEMETRY ", 1)[1])
                   for line in text.splitlines() if "PLAYER_TELEMETRY " in line]
    if any(record.get("schema") != SCHEMA for record in records):
        raise ValueError("Telemetry schema mismatch")
    labels = [record["checkpoint"] for record in records]
    if len(labels) != len(set(labels)):
        raise ValueError("Duplicate telemetry checkpoints")
    return records

def compare(reference, native, tolerance_fx12=8192):
    ds, port = read_records(reference), read_records(native)
    by_checkpoint = {row["checkpoint"]: row for row in port}
    out = {"schema": SCHEMA, "reference": str(reference), "native": str(native),
           "position_tolerance_fx12": tolerance_fx12, "checkpoints": []}
    for expected in ds:
        label = expected["checkpoint"]
        actual = by_checkpoint.get(label)
        if actual is None:
            out["checkpoints"].append({"checkpoint": label, "status": "MISSING"});continue
        row = {"checkpoint": label, "status": "SAME_LOCATION", "deltas": {}}
        for obj, fields in [("player", PLAYER_FIELDS), ("camera", CAMERA_FIELDS)]:
            for field in fields:
                a, b = expected[obj][field], actual[obj][field]
                delta = [y-x for x,y in zip(a,b)] if isinstance(a,list) else b-a
                row["deltas"][obj+"."+field] = delta
        pos_delta = row["deltas"]["player.position_fx12"]
        row["same_location"] = max(map(abs,pos_delta)) <= tolerance_fx12 and actual["level"] == expected["level"]
        row["native_root_minus_ground_fx12"] = actual["player"]["position_fx12"][1]-actual["player"]["ground_y_fx12"]
        row["ds_root_minus_ground_fx12"] = expected["player"]["position_fx12"][1]-expected["player"]["ground_y_fx12"]
        row["ground_delta_fx12"] = row["deltas"]["player.ground_y_fx12"]
        # Geometry comparisons require same locations; camera values remain
        # reported independently and are never silently normalized or ignored.
        if not row["same_location"]:
            row["status"] = "DIFFERENT_LOCATION"
        elif any(row["deltas"]["player."+field] != 0 for field in ["ground_y_fx12","sink_depth_fx12","body_yoffset_fx12","character","body_model_id"]):
            row["status"] = "PLAYER_DIFFERENCE"
        row["body_matrices_identical"] = expected["player"]["body_matrices_fx12"] == actual["player"]["body_matrices_fx12"]
        row["camera_fields_identical"] = expected["camera"] == actual["camera"]
        row["player_fields_identical"] = expected["player"] == actual["player"]
        row["ds_body_root_world_fx12"] = [None if matrix is None else [v*8 for v in matrix[9:12]] for matrix in expected["player"]["body_matrices_fx12"]]
        row["native_body_root_world_fx12"] = [None if matrix is None else [v*8 for v in matrix[9:12]] for matrix in actual["player"]["body_matrices_fx12"]]
        if row["same_location"]:
            row["status"] = "IDENTICAL_FIELDS" if row["player_fields_identical"] and row["camera_fields_identical"] else "SAME_LOCATION_WITH_DIFFERENCES"
        out["checkpoints"].append(row)
    out["comparison_complete"] = bool(ds) and all(r["status"] not in ["MISSING","DIFFERENT_LOCATION"] for r in out["checkpoints"])
    # This is evidence, never a gameplay PASS inferred from partial rows.
    return out

if __name__ == "__main__":
    ap=argparse.ArgumentParser(description=__doc__)
    sub=ap.add_subparsers(dest="command",required=True)
    inspect=sub.add_parser("inspect");inspect.add_argument("ram",type=Path)
    header=sub.add_parser("emit-header");header.add_argument("output",type=Path)
    route=sub.add_parser("emit-route-header");route.add_argument("route",type=Path);route.add_argument("output",type=Path)
    diff=sub.add_parser("compare");diff.add_argument("reference",type=Path);diff.add_argument("native",type=Path);diff.add_argument("--tolerance-fx12",type=int,default=8192)
    args=ap.parse_args()
    if args.command=="inspect": print(json.dumps(inspect_ram(args.ram),indent=2))
    elif args.command=="emit-header": emit_header(args.output)
    elif args.command=="emit-route-header": emit_route_header(args.route,args.output)
    else: print(json.dumps(compare(args.reference,args.native,args.tolerance_fx12),indent=2))
