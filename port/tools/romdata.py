#!/usr/bin/env python3
"""Emit the ROM data constants the gate-4b slice references.

These are read-only tables in the arm9 image (sine table, identity matrices,
texture-matrix constants). They are Nintendo's bytes, so they are never
committed: this reads the local decompressed arm9 (extracted/arm9_dec.bin,
flat image based at 0x02000000) and writes a C file under the build tree.
"""

import os
import pathlib
import struct
import sys

# extracted/arm9_dec.bin: the DECOMPRESSED arm9, flat at base 0x02004000
# (verified by two code anchors: Copy36Bytes @0x0205a548, DecompressLZ16
# @0x0205a754). extracted/dsd/arm9/arm9.bin is the COMPRESSED payload
# (arm9.yaml: compressed true) and must not be read directly. Addresses at
# or past bss_start are runtime-initialized and belong in the HAL.
BASE = 0x02004000
BSS_START = 0x0209B000  # config/arm9/delinks.txt .bss boundary

# (symbol address, byte length, C element type). BSS addresses do not belong
# here -- they are runtime-initialized and live in the HAL as storage.
TABLES = [
    (0x02075650, 32, "unsigned short"), # standard button mapping
    (0x02075670, 32, "unsigned short"), # touch mapping
    (0x02075690, 32, "unsigned short"), # dual-hand mapping
    (0x020756b0, 32, "short"), # D-pad direction angles

    (0x02075230, 6, "short"), # coin popup actor IDs, three kinds
    (0x02075238, 12, "int"), # value of the three coin kinds
    (0x02075250, 8, "char"), # per-character voice bases
    (0x02075298, 0x34, "char", ["SUBLEVEL_LEVEL_TABLE"]), # level IDs for52 sublevels
    (0x02092110, 0x2c, "char"),    # contiguous mutable stage/player settings, before g_profile_STAGE
    (0x02075264, 0x34, "char"),    # sublevel part index, GetLevelPart

    (0x0208E420, 0x78, "char"),    # sound state + ten {playerID,maxSeq} defaults
    (0x020755BC, 4, "char"),       # character exit-wipe types
    (0x02075638, 24, "char"),      # next-level override records
    (0x02086384, 256, "short"),    # sequence volume lookup (128 entries)
    (0x02086CC8, 8, "int"),        # camera interpolation parameters
    (0x02086D50, 8, "int"),        # alternate camera interpolation parameters
    (0x02092144, 8, "short"),      # four mutable player health values
    (0x02092664, 4, "unsigned short"), # current scene ID + padding
    (0x0208EB54, 4, "char"),       # temporary archive mount index (-1) and padding
    (0x0208EDF8, 8, "char"),       # LZ77 marker string + alignment padding
    (0x02099FC4, 8, "short"),      # particle perpendicular basis vector + padding
    (0x02099FA4, 2, "unsigned short"), # sound pan parameter
    (0x02099FA8, 4, "int"),        # sound attenuation near distance
    (0x02099FAC, 4, "int"),        # sound attenuation far distance
    (0x02099FB0, 4, "int"),        # sound state counter

    # A fourth column names ROM symbols the decomp spells by NAME rather than
    # by address. Model's migrated constructor assigns IDENTITY_MATRIX4X3, not
    # data_02082128, so the alias is emitted here beside the definition rather
    # than in a HAL file: a HAL alias would point at a symbol port_refcheck
    # cannot find in src/ or include/, because this datum is generated and
    # deliberately kept out of git.
    (0x02082128, 48, "int", ["IDENTITY_MATRIX4X3"]),  # Model ctor default Matrix4x3
    (0x02082190, 48, "int"),        # matrix Render uses for a NULL argument
    (0x020994E0, 1025 * 2, "unsigned short"),  # atan(y/x), indices 0..1024
    (0x02082214, 0x4000, "short"),  # s16 trig table the material bind indexes
    (0x020755A0, 12, "char"),       # OBJ width table (shape x size)
    (0x020755AC, 12, "char"),       # OBJ height table
]


def main():
    root = pathlib.Path(sys.argv[2] if len(sys.argv) > 2 else os.environ.get('SM64DS_DECOMP_DIR') or
                        pathlib.Path(__file__).resolve().parents[2] / 'sm64ds-decomp')
    img = root / "extracted/arm9_dec.bin"
    if not img.exists():
        sys.exit(f"missing {img} -- extract the ROM first")
    anchor = img.read_bytes()
    a = 0x0205A548 - BASE
    if anchor[a:a + 4] != b"\x0c\x10\xb0\xe8":
        sys.exit("arm9_dec.bin failed the Copy36Bytes anchor -- wrong image/base")
    for addr, length, _, *_rest in TABLES:
        if addr + length > BSS_START:
            sys.exit(f"{addr:#x}+{length:#x} crosses into BSS -- not file-backed")
    data = img.read_bytes()
    out_path = pathlib.Path(sys.argv[1]) if len(sys.argv) > 1 else (
        root / "build/port/host-src/romdata.c")
    out_path.parent.mkdir(parents=True, exist_ok=True)

    lines = ["/* GENERATED by port/tools/romdata.py from extracted/arm9_dec.bin.",
             " * ROM constants stay out of git; regenerate locally. */", ""]
    for addr, length, ctype, *rest in TABLES:
        if addr == 0x02082214:
            # Retail Flower020c35e8 sign-extends its angle index before a
            # four-byte table stride. Negative indices read up to8192 bytes
            # before FX_SinCosTable. Preserve those original neighboring
            # bytes, rather than native linker-dependent memory.
            blob = data[addr - BASE - 0x2000:addr - BASE + length]
            if len(blob) != 0x2000 + length:
                sys.exit("short read for signed trigonometric-table window")
            vals = struct.unpack("<" + "h" * (len(blob) // 2), blob)
            body = ", ".join(str(v) for v in vals)
            lines.append(f"short sm64ds_signed_trig_window[{len(vals)}] = {{ {body} }};")
            lines.append('__asm__(".global data_02082214\\n.set data_02082214, sm64ds_signed_trig_window+8192");')
            continue
        off = addr - BASE
        blob = data[off:off + length]
        if len(blob) != length:
            sys.exit(f"short read at {addr:#x}")
        fmt = {"int": "<i", "short": "<h", "unsigned short": "<H", "char": "<b"}[ctype]
        width = struct.calcsize(fmt)
        vals = [struct.unpack_from(fmt, blob, i)[0] for i in range(0, length, width)]
        name = f"data_{addr:08x}"
        body = ", ".join(str(v) for v in vals)
        lines.append(f"{ctype} {name}[{len(vals)}] = {{ {body} }};")
        if addr in (0x02092110, 0x0208e420):
            # The recovered code names both this block and its interior words.
            # GCC aliases must share storage, not independent initialized arrays.
            lines.append("#ifndef _MSC_VER")
            for offset in range(4, 0x2c if addr == 0x0208e420 else length, 4):
                alias = f"data_{addr + offset:08x}"
                lines.append(f'__asm__(".global {alias}\\n.set {alias}, {name}+{offset}");')
            lines.append("#endif")
        # MSVC decorates a C symbol with a leading underscore and a C++ one with
        # its type, and callers of both spellings have to reach the same bytes,
        # so each alias is emitted in both decorations.
        # The datum's own name needs the C++ decoration too: a TU that declares
        # it as a Matrix4x3 rather than an int array decorates the reference by
        # type, and has to reach these same bytes.
        lines.append("#ifdef _MSC_VER")
        for alias in [name] + list(rest[0] if rest else []):
            for dec in (f'_{alias}', f'?{alias}@@3UMatrix4x3@@A'):
                lines.append(
                    f'#pragma comment(linker, "/alternatename:{dec}=_{name}")')
        # GCC/Itanium does not decorate data symbols, so only true renames
        # need anything, and a real alias is the portable spelling.
        lines.append("#else")
        for alias in list(rest[0] if rest else []):
            lines.append(f'extern {ctype} {alias}[{len(vals)}] '
                         f'__attribute__((alias("{name}")));')
        lines.append("#endif")
        lines.append("")
    out_path.write_text("\n".join(lines), encoding="ascii")
    print(f"romdata -> {out_path}")


if __name__ == "__main__":
    main()
