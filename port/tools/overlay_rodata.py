#!/usr/bin/env python3
"""Extract ov002 read-only tables with native relocations, preserving all aliases.

Generated bytes belong in the local build tree only. This deliberately rejects
function pointers, foreign-module references and missing relocation symbols;
those require their own ABI review rather than raw DS addresses.
"""
import argparse
from collections import defaultdict
from pathlib import Path
import re
import struct


def generate(root):
    cfg = root / "config/arm9/overlays/ov002"
    text = (cfg / "delinks.txt").read_text()
    m = re.search(r"\.rodata\s+start:0x([0-9a-f]+) end:0x([0-9a-f]+)", text)
    start, end = int(m[1],16), int(m[2],16)
    blob = (root / "extracted/overlays/overlay_0002.bin").read_bytes()
    names, targets = defaultdict(list), {}
    for line in (cfg / "symbols.txt").read_text().splitlines():
        m = re.fullmatch(r"([\w.]+) kind:(\S+) addr:0x([0-9a-f]+)", line)
        if not m:
            continue
        name, kind, addr = m[1], m[2], int(m[3],16)
        targets[addr] = (name,kind)
        if start <= addr < end:
            if not kind.startswith("data"):
                raise ValueError(f"non-data symbol inside rodata: {line}")
            names[addr].append(name)
    relocs = {}
    for line in (cfg / "relocs.txt").read_text().splitlines():
        m = re.match(r"from:0x([0-9a-f]+) kind:(\w+) to:0x([0-9a-f]+) module:(\S+)", line)
        if not m or not start <= int(m[1],16) < end:
            continue
        addr, target = int(m[1],16), int(m[3],16)
        if m[2] != "load" or m[4] != "overlay(2)" or target not in targets:
            raise ValueError(f"unsupported relocation: {line}")
        name, kind = targets[target]
        if kind != "bss" and not (kind.startswith("data") and (start <= target < end or target == 0x0210d6d0)):
            raise ValueError(f"unreviewed relocation target: {line}")
        raw = struct.unpack_from("<I", blob, addr - 0x020ad660)[0]
        if raw != target or addr % 4 or addr+4 > end:
            raise ValueError(f"unexpected pointer encoding: {line}")
        relocs[addr] = name
    if len(relocs) != 900:
        raise ValueError(f"unexpected ov002 rodata relocation count {len(relocs)}")
    lines = ['// Generated from local ov002 ROM; native data-pointer relocations.',
             'asm(R"TABLES(', '.pushsection .rodata.sm64ds_ov002,"a",%progbits', '.balign 4']
    cursor = start
    while cursor < end:
        for name in names[cursor]:
            lines += [f'.global {name}', f'.type {name}, %object', f'{name}:']
        if cursor in relocs:
            if any(names[cursor+i] for i in range(1,4)):
                raise ValueError("symbol in middle of pointer")
            lines.append(f'.word {relocs[cursor]}')
            cursor += 4
        else:
            stop = min(cursor+16,end)
            for boundary in range(cursor+1,stop):
                if names[boundary] or boundary in relocs:
                    stop = boundary
                    break
            raw = blob[cursor-0x020ad660:stop-0x020ad660]
            if len(raw) != stop-cursor:
                raise ValueError("short ROM read")
            lines.append('.byte '+','.join(str(v) for v in raw))
            cursor = stop
    # The sole initialized-data target is the12-byte material name. Preserve
    # it separately; the following data contains unrelated pointer tables.
    material = blob[0x0210d6d0-0x020ad660:0x0210d6dc-0x020ad660]
    if material != b"mat_w_ring\0\0":
        raise ValueError("unexpected material name target")
    lines += ['.popsection', '.pushsection .rodata.sm64ds_ov002_names,"a",%progbits',
              '.balign 4', '.global data_ov002_0210d6d0', 'data_ov002_0210d6d0:',
              '.byte '+','.join(str(v) for v in material), '.popsection', ')TABLES");', '']
    return "\n".join(lines)


if __name__ == "__main__":
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("root", type=Path)
    ap.add_argument("output", type=Path)
    args = ap.parse_args()
    args.output.write_text(generate(args.root))
