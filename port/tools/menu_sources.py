#!/usr/bin/env python3
"""Generate the retail menu command dispatcher with its proven pointer ABI.

The original source drops r0 at 020cc970. Retail carries the freshly allocated
0xcc-byte file buffer from operator_new2 through to func_ov007_020cc0e4.
Keep src/ byte-matching sources unchanged; this is a native port adaptation.
"""
import os
from pathlib import Path
import argparse
import re
import struct


def generate(source: Path, output: Path):
    text = source.read_text()
    replacements = {
        "extern void func_ov007_020cc0e4(void);":
        "extern void func_ov007_020cc0e4(void *files);",
        "        func_ov007_020cc0e4();":
        "        func_ov007_020cc0e4(sb);",
    }
    for before, after in replacements.items():
        if text.count(before) != 1:
            raise ValueError(f"Menu dispatcher source changed: {before}")
        text = text.replace(before, after)
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text("/* Generated by port/tools/menu_sources.py. */\n" + text)



def adapt_generated_tree(directory: Path):
    """Preserve C source semantics after hostgen's C++ MMIO translation.

    C's f() means unspecified parameters; C++ f() means no parameters.
    These ten integer/pointer-only call interfaces retain the original C
    declarations' return types here. Return-type reconstruction is separate.
    No floating argument or reference ABI is involved.
    """
    unspecified = {
        "020c02d8", "020c1d78", "020c3d1c", "020c937c", "020c1180",
        "020aea4c", "020b1f2c", "020c421c", "020c9214", "020c184c",
    }
    for path in directory.rglob("*.cpp"):
        text = path.read_text()
        if path.name == "func_020531a4.cpp":
            # Shared hostgen now handles both indexed SDK operand stores.
            for index,value in [(0,'0'),(1,'a')]:
                expected=f'NTR_MMIO(int, (0x40002b8 + sizeof(int) * ({index}))) = {value};'
                if text.count(expected)!=1:
                    raise ValueError("Shared square-root parameter translation changed")
        # Volatile typedefs in the original grid emitters/macros are not
        # recognized by shared hostgen. They must feed the native GX decoder,
        # not merely write the mapped IO mirror. Keep original source intact.
        text = re.sub(r"\*\s*\(vu(8|16|32|64)\s*\*\s*\)\s*(0x0?4[0-9a-fA-F]+)\b",
                      lambda m: f"NTR_MMIO(uint{m[1]}_t, {m[2]})", text)
        if re.search(r"from src/[^\n]+\.c\n", text):
            for address in unspecified:
                text = text.replace(f"extern int func_ov007_{address}();",
                                    f"extern int func_ov007_{address}(...);")
        if path.name == "func_ov007_020c7d60.cpp":
            before = "int sqrt_raw, len, dot, s, rest, NTR_MMIO(int, 0x40002b4);"
            if text.count(before) != 1:
                raise ValueError("Unexpected square-root local declaration")
            text = text.replace(before, "int sqrt_raw, len, dot, s, rest, *p_sqrt;")
        if path.name == "func_ov007_020c9110.cpp":
            text = re.sub(r"\bthis\b", "self", text)
        if path.name == "d_s_dsmt.cpp":
            text = text.replace("extern int data_ov007_021032e8[];", "extern int _ZTV9dScDSMT_c[];")
            text = text.replace("extern int data_ov007_021032b0[];", "extern int _ZTVN9dScDSMT_c15graphCallback_cE[];")
            text = text.replace("(int)data_ov007_021032e8", "(int)(_ZTV9dScDSMT_c + 2)")
            text = text.replace("(int)data_ov007_021032b0", "(int)(_ZTVN9dScDSMT_c15graphCallback_cE + 2)")
        if path.name == "_ZN9dScDSMT_c8BehaviorEv.cpp":
            # Linker labels overlay_64/66 encode hexadecimal IDs; retail
            # literal loads at020cc3d4/3dc read100/102 from020cc450/454.
            rom=(Path(os.environ.get('SM64DS_DECOMP_DIR') or Path(__file__).resolve().parents[2] / 'sm64ds-decomp')/"extracted/overlays/overlay_0007.bin").read_bytes()
            if struct.unpack_from("<2I",rom,0x020cc450-0x020ad660)!=(100,102):
                raise ValueError("Menu VS overlay literals changed")
            for old,new in [(64,100),(66,102)]:
                before=f"LoadOverlay({old});"
                if text.count(before)!=1:raise ValueError("Menu VS overlay call changed")
                text=text.replace(before,f"LoadOverlay({new});")
            # Retail preserves the session index in r0 across two consecutive
            # calls at 020cc310/314 and 020cc31c/320. The legacy prototypes in
            # decl_common.h incorrectly discard these integer parameters.
            declarations = ('extern "C" u16* sm64ds_menu_input(int) asm("func_0203dabc");\n'
                            'extern "C" int sm64ds_menu_touch(int) asm("func_0203dae4");\n')
            text = text.replace("s32 dScDSMT_c::Behavior()", declarations + "s32 dScDSMT_c::Behavior()")
            text = text.replace("    func_0203da9c();\n", "")
            text = text.replace("func_0203dabc()", "sm64ds_menu_input(func_0203da9c())")
            text = text.replace("func_0203dae4()", "sm64ds_menu_touch(func_0203da9c())")
        if path.name == "func_02042fe4.cpp":
            # ROM tail-call forwards the factory result unchanged in r0.
            text = text.replace("extern void func_02043098", "extern int func_02043098")
            text = text.replace("void func_02042fe4", "int func_02042fe4")
            text = text.replace("    func_02043098(a, 0, b, c);", "    return func_02043098(a, 0, b, c);")
        if path.name == "func_02017278.cpp":
            text = ('// Native equivalent of the ROM fader constructor chain.\n'
                    '#include "dFdDummy_c.h"\n#include <new>\n'
                    'extern "C" void func_02017278(void* storage) {\n'
                    '    ::new (storage) dFdDummy_c;\n}\n')
        if path.name == "ARMMathSaveState.cpp":
            for member,address in [("p0",0x4000290),("p8",0x4000298),("p10",0x40002b8)]:
                before = f"s->{member} = *(struct Pair*)0x{address:x};"
                if text.count(before)!=1:raise ValueError("Math state source changed")
                text = text.replace(before, f"s->{member} = Pair{{NTR_MMIO(u32, 0x{address:x}), NTR_MMIO(u32, 0x{address+4:x})}};")
        if path.name == "func_02017e94.cpp":
            text = ('#include "unmatched/native_overlay.h"\n#include <cstdio>\n#include <cstdlib>\n'
                    'extern "C" void func_02017e94(int id) {\n'
                    ' auto result=sm64ds_try_unload_overlay(id);\n'
                    ' if(result!=OVERLAY_OK && result!=OVERLAY_NOT_LOADED) {\n'
                    '  std::fprintf(stderr,"menu unload %d failed: %d\\n",id,result);std::abort();\n'
                    ' }\n}\n')
        if path.name == "func_0201a458.cpp":
            text = ('// Retail reserves 0x0211d9c0..0x02140d80 for this separate heap.\n'
                    '#include "Heap.h"\n'
                    'extern "C" void* data_0209d524;\n'
                    'alignas(32) static unsigned char menu_minigame_heap[0x2140d80-0x211d9c0];\n'
                    'extern "C" void* func_0201a458() {\n'
                    ' data_0209d524=Heap::CreateRootHeap(menu_minigame_heap,sizeof(menu_minigame_heap));\n'
                    ' return data_0209d524;\n}\n')
        if path.name == "func_ov007_020c1db0.cpp":
            text = text.replace("extern void func_0205f040(void);", "extern void sm64ds_menu_sample_touch(u16* sample);")
            text = text.replace("        func_0205f040();\n        func_0205efc0(tmp);", "        sm64ds_menu_sample_touch(tmp);")
        if path.name == "func_02045d9c.cpp":
            # Native allocations are regular ARM11 memory, with no DS DTCM.
            text = text.replace("    _ZN4CP1510EnableDTCMEv();", "    /* Native memory does not require enabling ARM9 DTCM. */")
        if path.name == "func_ov007_020ccab4.cpp":
            text = '#include <cstdio>\n#include <cstdlib>\n' + text
            text = text.replace('return _ZN4Heap8AllocateEj(data_020a0ea0, a);',
                'if(std::getenv("MENU_ALLOC_TRACE"))std::fprintf(stderr,"menu allocate size=%d heap=%08x\\n",a,data_020a0ea0);\n'
                '    int result=_ZN4Heap8AllocateEj(data_020a0ea0, a);\n'
                '    if(std::getenv("MENU_ALLOC_TRACE"))std::fprintf(stderr,"menu allocated=%08x\\n",result);\n'
                '    return result;')
        if path.name == "func_ov007_020c99d8.cpp":
            # ROM 020c9a1c calls the cell allocator and returns its r0 unchanged.
            text = text.replace("extern void func_ov007_020c3550", "extern int func_ov007_020c3550")
            text = text.replace("    func_ov007_020c3550((int)((char *)ip + 0xc), b, c, d);",
                                "    return func_ov007_020c3550((int)((char *)ip + 0xc), b, c, d);")
        if path.name == "func_ov007_020c3550.cpp":
            # ROM 020c3570..3594 retains the allocated cell pointer in r0.
            text = text.replace("void func_ov007_020c3550", "int func_ov007_020c3550")
            text = text.replace("  *(unsigned char*)(p+0xa) = 0;", "  *(unsigned char*)(p+0xa) = 0;\n  return (int)p;")
        if path.name == "func_ov007_020bc7dc.cpp":
            text = '#include <cstdio>\n#include <cstdlib>\n' + text
            text = text.replace('    func_0204531c(model, quot);',
                '    static unsigned trace_count;\n'
                '    if(std::getenv("MENU_MODEL_TRACE") && trace_count++<16)std::fprintf(stderr,"menu blend c=%p flags=%x buffer=%x model=%p transforms=%x aux=%x weight=%d\\n",c,*(unsigned*)(c+0x9c),*(unsigned*)(c+0xc),model,((unsigned*)model)[3],((unsigned*)model)[4],quot);\n'
                '    func_0204531c(model, quot);')
        if path.name == "func_02059eb0.cpp":
            text = text.replace("(unsigned char *)0x27ffc80", "ntr::xlate<unsigned char>((void*)0x027ffc80u)")
        path.write_text(text)
    dispatcher = directory / "src/func_ov007_020cc600.cpp"
    generate(dispatcher, dispatcher)

if __name__ == "__main__":
    parser = argparse.ArgumentParser()
    parser.add_argument("source", type=Path)
    parser.add_argument("--tree", action="store_true")
    parser.add_argument("output", type=Path, nargs="?")
    args = parser.parse_args()
    if args.tree:
        adapt_generated_tree(args.source)
    else:
        if args.output is None: parser.error("output required without --tree")
        generate(args.source, args.output)
