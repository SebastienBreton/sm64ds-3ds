// DS assembly avoids byte stores because of physical DS VRAM bus restrictions.
// Native buffers are ordinary mapped RAM; copy exactly the requested bytes,
// retaining both edge bytes for odd alignments and odd lengths.
extern "C" void CpuCopy8(const void *src, void *dst, unsigned count) {
    if (!count) return;
    if (ntr::memory_bus_required(src, dst)) {
        ntr::MemoryTransferBus bus;
        ntr::memory_copy8(bus, reinterpret_cast<uintptr_t>(src), reinterpret_cast<uintptr_t>(dst), count);
        return;
    }
    const auto *s = ntr::xlate<const unsigned char>(src);
    auto *d = ntr::xlate<unsigned char>(dst);
    for (unsigned i = 0; i < count; ++i) d[i] = s[i];
}

