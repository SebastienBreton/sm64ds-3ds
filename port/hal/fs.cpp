// castle-30fps: small ROM files opened through the FS handle API are kept in
// host RAM after their first open. The DS re-reads some of them every frame
// from the cartridge (e.g. a 2D palette in the painting rooms), which costs a
// fraction of a millisecond there but an SD open (~10 ms) per call here.
// ROM files are immutable; entries with open handles are never evicted.
static const u32 NATIVE_CACHED_FILE = 0x43414348;
static const u32 NATIVE_PREFETCH_FILE = 0x50524546; // recroom-lag: served from g_prefetch (immutable)
struct CachedRomFile { u32 id; u8 *data; u32 size, open; unsigned long long age; };
enum { ROM_CACHE_SLOTS = 64, ROM_CACHE_MAX_FILE = 64 * 1024, ROM_CACHE_BUDGET = 128 * 1024 };
static CachedRomFile rom_cache[ROM_CACHE_SLOTS];
static u32 rom_cache_bytes;
static unsigned long long rom_cache_clock;
static bool rom_cache_enabled(){
    static const bool enabled=[](){const char* v=getenv("SM64DS_ROM_FILE_CACHE");return !v || strcmp(v,"0")!=0;}();
    return enabled;
}
static int rom_cache_find(u32 id){
    for (int i=0;i<ROM_CACHE_SLOTS;++i) if (rom_cache[i].data && rom_cache[i].id==id) return i;
    return -1;
}
static int rom_cache_insert_from(u32 id, FILE *f, const u8 *bytes, u32 size);
static int rom_cache_insert(u32 id, FILE *f, u32 size){ return rom_cache_insert_from(id,f,nullptr,size); }
static int rom_cache_insert_bytes(u32 id, const u8 *bytes, u32 size){ return rom_cache_insert_from(id,nullptr,bytes,size); }
static int rom_cache_insert_from(u32 id, FILE *f, const u8 *bytes, u32 size){
    for (;;) {
        int vacant=-1,oldest=-1;
        for (int i=0;i<ROM_CACHE_SLOTS;++i) {
            if (!rom_cache[i].data) { if (vacant<0) vacant=i; continue; }
            if (!rom_cache[i].open && (oldest<0 || rom_cache[i].age<rom_cache[oldest].age)) oldest=i;
        }
        if (vacant>=0 && rom_cache_bytes+size<=ROM_CACHE_BUDGET) {
            u8 *data=(u8*)malloc(size?size:1);
            if (!data) return -1;
            if (bytes) { if (size) memcpy(data,bytes,size); }
            else if (size && fread(data,1,size,f)!=size) { free(data); return -1; }
            rom_cache[vacant]={id,data,size,0,++rom_cache_clock};rom_cache_bytes+=size;
            return vacant;
        }
        if (oldest<0) return -1;
        rom_cache_bytes-=rom_cache[oldest].size;free(rom_cache[oldest].data);rom_cache[oldest]={};
    }
}
